import { useParams, Link } from 'react-router-dom';
import { Disc3, Heart, ListPlus } from 'lucide-react';
import { MediaCard } from '@/components/cards/MediaCard';
import { Shelf } from '@/components/cards/Shelf';
import { TrackList } from '@/components/cards/TrackList';
import { CollectionHeader } from '@/components/collection/CollectionHeader';
import { PlayActions } from '@/components/collection/PlayActions';
import { playCollection } from '@/components/collection/playCollection';
import { Button } from '@/components/common/Button';
import { EmptyState } from '@/components/common/EmptyState';
import { useLibrary } from '@/hooks/usePlayer';
import { albumCover, albumsByArtist, getAlbum, getArtist, getTracks } from '@/services/catalog';
import { libraryActions } from '@/state/libraryStore';
import { ui } from '@/state/uiStore';
import { formatDate, formatTotal, plural } from '@/utils/format';

export default function AlbumPage() {
  const { id = '' } = useParams();
  const album = getAlbum(id);
  const saved = useLibrary((s) => Boolean(s.savedAlbums[id]));
  if (!album) return <EmptyState icon={<Disc3 className="h-7 w-7" />} title="Album not found">This album doesn’t exist or was removed.</EmptyState>;
  const artist = getArtist(album.artistId);
  const tracks = getTracks(album.trackIds);
  const total = tracks.reduce((a, t) => a + t.duration, 0);
  const context = { type: 'album' as const, id: album.id, name: album.title, href: `/album/${album.id}` };
  const more = albumsByArtist(album.artistId).filter((a) => a.id !== album.id);

  return (
    <div className="space-y-10">
      <CollectionHeader
        cover={albumCover(album)}
        kind={album.type === 'single' ? 'Single' : album.type === 'ep' ? 'EP' : 'Album'}
        title={album.title}
        description={album.description}
        palette={album.palette}
        meta={
          <>
            {artist && (
              <Link to={`/artist/${artist.id}`} className="font-bold text-fg hover:underline">
                {artist.name}
              </Link>
            )}
            <span>· {new Date(album.releaseDate).getFullYear()}</span>
            <span>· {plural(tracks.length, 'song')}, {formatTotal(total)}</span>
          </>
        }
        actions={
          <>
            <PlayActions trackIds={album.trackIds} context={context} />
            <Button
              size="lg"
              variant="ghost"
              aria-pressed={saved}
              onClick={() => {
                libraryActions.toggleSaveAlbum(album.id);
                ui.toast(saved ? 'Removed from your library' : 'Saved to your library', 'success');
              }}
              icon={<Heart className="h-5 w-5" fill={saved ? 'currentColor' : 'none'} />}
              className={saved ? '!text-ember' : ''}
            >
              {saved ? 'Saved' : 'Save'}
            </Button>
            <Button size="lg" variant="ghost" onClick={() => ui.openAddToPlaylist(album.trackIds)} icon={<ListPlus className="h-5 w-5" />}>
              Add to playlist
            </Button>
          </>
        }
      />
      <TrackList tracks={tracks} context={context} showCover={false} showAlbum={false} />
      <p className="text-xs text-subtle">
        Released {formatDate(album.releaseDate)} · ℗ {new Date(album.releaseDate).getFullYear()} {album.label}. Original demo music generated by MusicWave.
      </p>
      {more.length > 0 && artist && (
        <Shelf title={`More by ${artist.name}`}>
          {more.map((a) => (
            <MediaCard key={a.id} href={`/album/${a.id}`} cover={albumCover(a)} title={a.title} subtitle={String(new Date(a.releaseDate).getFullYear())} onPlay={() => playCollection(a.trackIds, { type: 'album', id: a.id, name: a.title, href: `/album/${a.id}` })} />
          ))}
        </Shelf>
      )}
    </div>
  );
}
